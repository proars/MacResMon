#!/usr/bin/env bash
# Builds "MacResMon.app": the web UI (../dist) + the Swift shell + a bundled macmon.
# Needs: Node (npm), Swift (Command Line Tools are enough) and macmon (brew install macmon).
# The app is ad-hoc signed, so it runs on this Mac; to distribute it, sign with a Developer ID and notarize.
set -euo pipefail
cd "$(dirname "$0")"

MACMON="$(readlink -f "${MACMON_BIN:-$(command -v macmon || true)}" 2>/dev/null || true)"
[ -x "$MACMON" ] || { echo "macmon not found: run 'brew install macmon' (or set MACMON_BIN)" >&2; exit 1; }

echo "== web UI"
(cd .. && npm run build)

echo "== Swift build"
swift build -c release
BIN="$(swift build -c release --show-bin-path)/MacResMon"

APP="build/MacResMon.app"
VERSION="$(node -p "require('../package.json').version")"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources/bin" "$APP/Contents/Resources/licenses"
cp "$BIN" "$APP/Contents/MacOS/MacResMon"
cp -R ../dist "$APP/Contents/Resources/dist"
# The icon is generated by Tools/make-icon.sh (run `npm run native:icon` to redraw it).
[ -f Resources/AppIcon.icns ] || ./Tools/make-icon.sh
cp Resources/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"
cp "$MACMON" "$APP/Contents/Resources/bin/macmon"
# macmon is MIT licensed: ship its notice next to the binary.
LICENSE_SRC="$(dirname "$MACMON")/../LICENSE"
[ -f "$LICENSE_SRC" ] && cp "$LICENSE_SRC" "$APP/Contents/Resources/licenses/macmon-LICENSE"
cp ../LICENSE "$APP/Contents/Resources/licenses/MacResMon-LICENSE"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleName</key><string>MacResMon</string>
  <key>CFBundleDisplayName</key><string>MacResMon</string>
  <key>CFBundleIdentifier</key><string>com.macresmon.app</string>
  <key>CFBundleExecutable</key><string>MacResMon</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundleVersion</key><string>$VERSION</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <key>LSApplicationCategoryType</key><string>public.app-category.utilities</string>
  <key>NSHighResolutionCapable</key><true/>
</dict></plist>
PLIST

codesign --force --deep --sign - "$APP" 2>&1 | grep -v "replacing existing signature" || true
echo "== done: $PWD/$APP"
